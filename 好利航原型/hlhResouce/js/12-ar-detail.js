    var wb=v('ar-f-wb'),fee=v('ar-f-fee'),amt=v('ar-f-amt'),cur=v('ar-f-cur'),ft=v('ar-f-ftime'),rk=v('ar-f-rk');
    if(!wb||!fee||!amt||!cur||!ft){showToast(tr('请完整填写必填项'));return;}
    var ftime=ft.replace('T',' ')+(ft.length<=16?':00':'');
    var row=_arEditingRow;
    if(row){
        row.fee=fee;row.amt=amt;row.cur=cur;row.ftime=ftime;row.rk=rk;
        /* 金额改了未核销要跟着回算，不然汇总行的「应收-已核销-未核销」三个数对不上 */
        row.unused=arFmt(arNum(amt)-arNum(row.used));
        _arEditingRow=null;
        closeCrudModal();refreshArDetailView();showToast(tr('调整成功'));
        return;
    }
    /* 客户名称/业务员/结算周期不让手填，按运单号带出来；带不到就留空，不臆造 */
    var ref=arLookupByWaybill(wb);
