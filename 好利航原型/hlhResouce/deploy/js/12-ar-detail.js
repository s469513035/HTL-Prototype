/* ===== 货物属性带报关类型：种子表只维护到 bl/goods/cargo/pack/vol/wt，
 * 报关类型没单独维护 —— 按运单号稳定推导（原型口径，正式版从运单报关信息读）。 ===== */
function arCargoWithCustoms(wb){
    var c=arCargoOf(wb)||{};
    if(c.customs==null){
        var s=String(wb||''),n=0;
        for(var i=0;i<s.length;i++)n+=s.charCodeAt(i)*(i+1);
        c.customs=['一般贸易','快件报关','电商报关'][n%3];
    }
    return c;
}

